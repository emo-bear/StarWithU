export function mockSettings(events) {
  const first = events[0]?.date || new Date().toISOString().slice(0, 10)
  const [y, m, d] = first.split('-').map(Number)
  const now = new Date()
  const d0 = new Date(y, m - 1, d)
  const d1 = new Date(now.getFullYear(), now.getMonth(), now.getDate())
  const days = Math.round((d1 - d0) / 86400000) + 1
  return {
    dataDir: '（浏览器预览模式，未连接本地数据库）',
    eventCount: events.length,
    imageCount: 0,
    loveStart: first,
    spanDays: days,
  }
}
